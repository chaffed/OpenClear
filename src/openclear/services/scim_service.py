"""SCIM 2.0 provisioning (RFC 7643/7644; SDK_PLAN.md phase F): a bank's directory (Okta,
Entra ID, ...) creates, updates and deactivates people in OpenClear for one SSO connection,
and pushes its groups.

- **Authentication:** a bearer token per connection, generated by a bank admin on the
  connection's page and shown once (only its SHA-256 is kept). The token embeds the bank
  and connection ids (`scim_<bank>_<connection>_<secret>`), so the request binds to the
  right bank before reading anything, like API client ids.
- **Access comes from groups:** a person's SCIM groups are matched against the
  connection's group mappings exactly as a sign-in's groups are (sso_service): the
  lowest-priority match gives their security group, in the connection's scope (bank-wide or
  one customer). No matching group, or `active: false`, deactivates their membership here
  and ends their sessions.
- **Nothing is deleted:** DELETE deactivates, so the person stays on the record for the
  action log. A person is matched to an existing OpenClear user by email, since people
  can belong to more than one bank.
- **Lenient about attributes it doesn't use** (title, department, ...), as directories send
  many; strict about the ones it does."""

import hashlib
import re
import secrets
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from openclear.auth.security import hash_password
from openclear.domain.sso_connection import ScimGroup, ScimGroupMember, ScimUser, SsoConnection, SsoGroupMapping
from openclear.domain.tenant_membership import TenantMembership
from openclear.domain.user import User

USER_SCHEMA = "urn:ietf:params:scim:schemas:core:2.0:User"
GROUP_SCHEMA = "urn:ietf:params:scim:schemas:core:2.0:Group"
LIST_SCHEMA = "urn:ietf:params:scim:api:messages:2.0:ListResponse"
PATCH_SCHEMA = "urn:ietf:params:scim:api:messages:2.0:PatchOp"
ERROR_SCHEMA = "urn:ietf:params:scim:api:messages:2.0:Error"
MAX_PAGE = 200

_TOKEN = re.compile(r"^scim_([0-9a-f]{32})_([0-9a-f]{32})_([A-Za-z0-9_-]{20,})$")


class ScimError(Exception):
    """An error the SCIM client should see, with SCIM's status and scimType."""

    def __init__(self, status: int, detail: str, scim_type: str | None = None) -> None:
        super().__init__(detail)
        self.status, self.detail, self.scim_type = status, detail, scim_type

    def body(self) -> dict:
        body = {"schemas": [ERROR_SCHEMA], "status": str(self.status), "detail": self.detail}
        if self.scim_type:
            body["scimType"] = self.scim_type
        return body


# --- Tokens --------------------------------------------------------------------------------


def _hash(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def issue_token(session: Session, connection: SsoConnection) -> str:
    """A new SCIM token for the connection, replacing any earlier one. Shown once."""
    token = f"scim_{connection.tenant_id.hex}_{connection.id.hex}_{secrets.token_urlsafe(32)}"
    connection.scim_token_hash = _hash(token)
    connection.scim_token_created_at = datetime.now(timezone.utc)
    session.flush()
    return token


def revoke_token(session: Session, connection: SsoConnection) -> None:
    connection.scim_token_hash, connection.scim_token_created_at = None, None
    session.flush()


def parse_token(token: str) -> tuple[uuid.UUID, uuid.UUID] | None:
    """(bank, connection) from a token's shape, before anything is read."""
    match = _TOKEN.match(token or "")
    return (uuid.UUID(match.group(1)), uuid.UUID(match.group(2))) if match else None


def authenticate(session: Session, token: str) -> SsoConnection:
    """The connection a token is for. The caller has already bound the session to the bank
    from parse_token."""
    ids = parse_token(token)
    connection = session.get(SsoConnection, ids[1]) if ids else None
    if (
        connection is None or connection.tenant_id != ids[0] or not connection.is_active or not connection.scim_token_hash
        or not secrets.compare_digest(connection.scim_token_hash, _hash(token))
    ):
        raise ScimError(401, "Invalid or revoked SCIM token.")
    return connection


# --- Access from groups --------------------------------------------------------------------


def _group_names(session: Session, scim_user: ScimUser) -> list[str]:
    return list(session.execute(
        select(ScimGroup.display_name).join(ScimGroupMember, ScimGroupMember.group_id == ScimGroup.id)
        .where(ScimGroupMember.scim_user_id == scim_user.id)
    ).scalars())


def sync_access(session: Session, connection: SsoConnection, scim_user: ScimUser) -> TenantMembership | None:
    """Sets the person's membership in the connection's scope from their SCIM groups, the
    way a sign-in does. Returns the membership, or None if they have no access."""
    from openclear.services import session_service

    mappings = session.execute(
        select(SsoGroupMapping).where(SsoGroupMapping.connection_id == connection.id)
    ).scalars().all()
    groups = set(_group_names(session, scim_user))
    matches = [m for m in mappings if m.external_group in groups]
    membership = session.execute(
        select(TenantMembership).where(
            TenantMembership.tenant_id == connection.tenant_id, TenantMembership.user_id == scim_user.user_id,
            (TenantMembership.customer_id == connection.customer_id) if connection.customer_id else TenantMembership.customer_id.is_(None),
        )
    ).scalars().first()
    if not scim_user.active or not matches:
        if membership is not None and membership.is_active:
            membership.is_active = False
            user = session.get(User, scim_user.user_id)
            session_service.revoke_all_sessions(session, user)
        session.flush()
        return None
    group_id = min(matches, key=lambda m: m.priority).security_group_id
    if membership is None:
        membership = TenantMembership(
            user_id=scim_user.user_id, tenant_id=connection.tenant_id, customer_id=connection.customer_id, security_group_id=group_id,
        )
        session.add(membership)
    else:
        if membership.security_group_id != group_id:
            membership.security_group_id = group_id
        membership.is_active = True
    session.flush()
    return membership


# --- Users ---------------------------------------------------------------------------------


def _location(base: str, kind: str, resource_id: uuid.UUID) -> str:
    return f"{base}/scim/v2/{kind}/{resource_id}"


def user_resource(session: Session, scim_user: ScimUser, base: str) -> dict:
    user = session.get(User, scim_user.user_id)
    groups = session.execute(
        select(ScimGroup).join(ScimGroupMember, ScimGroupMember.group_id == ScimGroup.id).where(ScimGroupMember.scim_user_id == scim_user.id)
    ).scalars().all()
    resource = {
        "schemas": [USER_SCHEMA],
        "id": str(scim_user.id),
        "userName": scim_user.user_name,
        "active": scim_user.active,
        "emails": [{"value": user.email, "type": "work", "primary": True}],
        "groups": [{"value": str(g.id), "display": g.display_name, "$ref": _location(base, "Groups", g.id)} for g in groups],
        "meta": {
            "resourceType": "User",
            "created": scim_user.created_at.isoformat() if scim_user.created_at else None,
            "lastModified": scim_user.updated_at.isoformat() if scim_user.updated_at else None,
            "location": _location(base, "Users", scim_user.id),
        },
    }
    if scim_user.external_id:
        resource["externalId"] = scim_user.external_id
    if scim_user.display_name:
        resource["displayName"] = scim_user.display_name
    if scim_user.given_name or scim_user.family_name:
        resource["name"] = {k: v for k, v in (("givenName", scim_user.given_name), ("familyName", scim_user.family_name)) if v}
    return resource


def _bool(value: Any) -> bool:
    # Entra ID sends "True"/"False" strings.
    return value.strip().lower() == "true" if isinstance(value, str) else bool(value)


def _email(payload: dict) -> str:
    emails = payload.get("emails") or []
    primary = next((e for e in emails if isinstance(e, dict) and e.get("primary")), None) or (emails[0] if emails else None)
    email = (primary.get("value") if isinstance(primary, dict) else None) or payload.get("userName") or ""
    email = str(email).strip().lower()
    if "@" not in email or len(email) > 255:
        raise ScimError(400, "A user needs an email address (emails, or a userName that is one).", "invalidValue")
    return email


def _apply_user(scim_user: ScimUser, payload: dict) -> None:
    if "userName" in payload:
        user_name = str(payload["userName"] or "").strip()
        if not user_name or len(user_name) > 255:
            raise ScimError(400, "userName is required.", "invalidValue")
        scim_user.user_name = user_name
    if "externalId" in payload:
        scim_user.external_id = (str(payload["externalId"]) or None) if payload["externalId"] is not None else None
    if "displayName" in payload:
        scim_user.display_name = str(payload["displayName"] or "")[:255] or None
    name = payload.get("name")
    if isinstance(name, dict):
        if "givenName" in name:
            scim_user.given_name = str(name["givenName"] or "")[:255] or None
        if "familyName" in name:
            scim_user.family_name = str(name["familyName"] or "")[:255] or None
    if "active" in payload:
        scim_user.active = _bool(payload["active"])


def _user_for_email(session: Session, connection: SsoConnection, email: str) -> User:
    user = session.execute(select(User).where(func.lower(User.email) == email)).scalar_one_or_none()
    if user is not None and user.is_service_account:
        raise ScimError(409, "That email belongs to an API client.", "uniqueness")
    if user is not None:
        # Only someone already a member here, in this connection's scope, is linked; anyone
        # else (in another organization, or bank staff seen from a customer's directory) is
        # added by an admin first, as with single sign-on (sso_service).
        scope = (TenantMembership.customer_id == connection.customer_id) if connection.customer_id else TenantMembership.customer_id.is_(None)
        member = session.execute(select(TenantMembership.id).where(
            TenantMembership.user_id == user.id, TenantMembership.tenant_id == connection.tenant_id, scope)).first()
        if member is None:
            raise ScimError(409, "Someone with that email already uses OpenClear elsewhere. An admin adds them here first; "
                                 "then the directory can manage them.", "uniqueness")
    if user is None:
        # Never usable for password sign-in: SCIM people sign in through the identity provider.
        user = User(email=email, hashed_password=hash_password(secrets.token_urlsafe(48)))
        session.add(user)
        session.flush()
    return user


def _set_email(session: Session, scim_user: ScimUser, email: str) -> None:
    user = session.get(User, scim_user.user_id)
    if user.email.lower() == email:
        return
    taken = session.execute(select(User.id).where(func.lower(User.email) == email)).first()
    if taken:
        raise ScimError(409, "Another user already has that email.", "uniqueness")
    # A person's email belongs to them across banks; only change it if this bank's directory
    # is the only place they're known.
    other_banks = session.execute(
        select(func.count()).select_from(TenantMembership).where(
            TenantMembership.user_id == user.id, TenantMembership.tenant_id != scim_user.tenant_id,
        )
    ).scalar_one()
    if other_banks:
        raise ScimError(409, "This person belongs to other organizations too, so their email can't be changed here.", "mutability")
    user.email = email


def create_user(session: Session, connection: SsoConnection, payload: dict) -> ScimUser:
    email = _email(payload)
    user_name = str(payload.get("userName") or email).strip()
    if session.execute(select(ScimUser.id).where(ScimUser.connection_id == connection.id, ScimUser.user_name == user_name)).first():
        raise ScimError(409, "A user with that userName already exists.", "uniqueness")
    user = _user_for_email(session, connection, email)
    if session.execute(select(ScimUser.id).where(ScimUser.connection_id == connection.id, ScimUser.user_id == user.id)).first():
        raise ScimError(409, "A user with that email already exists.", "uniqueness")
    scim_user = ScimUser(tenant_id=connection.tenant_id, connection_id=connection.id, user_id=user.id, user_name=user_name, active=True)
    _apply_user(scim_user, {**payload, "userName": user_name})
    session.add(scim_user)
    session.flush()
    sync_access(session, connection, scim_user)
    return scim_user


def get_user(session: Session, connection: SsoConnection, user_id: str) -> ScimUser:
    try:
        scim_user = session.get(ScimUser, uuid.UUID(user_id))
    except ValueError:
        scim_user = None
    if scim_user is None or scim_user.connection_id != connection.id:
        raise ScimError(404, "User not found.")
    return scim_user


def replace_user(session: Session, connection: SsoConnection, scim_user: ScimUser, payload: dict) -> ScimUser:
    _apply_user(scim_user, {"active": True, **payload})
    _set_email(session, scim_user, _email(payload))
    session.flush()
    sync_access(session, connection, scim_user)
    return scim_user


_SIMPLE_USER_PATHS = {"active", "username", "externalid", "displayname", "name.givenname", "name.familyname"}


def patch_user(session: Session, connection: SsoConnection, scim_user: ScimUser, payload: dict) -> ScimUser:
    for op in _operations(payload):
        kind, path, value = op
        if kind not in ("add", "replace"):
            continue  # removing an attribute OpenClear keeps is a no-op
        if path is None:
            if not isinstance(value, dict):
                raise ScimError(400, "A patch without a path needs an object value.", "invalidValue")
            _apply_user(scim_user, _flatten_user_value(value))
            emails = value.get("emails")
            if emails:
                _set_email(session, scim_user, _email({"emails": emails}))
            continue
        lowered = path.lower()
        if lowered in _SIMPLE_USER_PATHS:
            key = {"username": "userName", "externalid": "externalId", "displayname": "displayName", "active": "active"}.get(lowered)
            if key:
                _apply_user(scim_user, {key: value})
            else:
                _apply_user(scim_user, {"name": {"givenName" if lowered.endswith("givenname") else "familyName": value}})
        elif lowered.startswith("emails"):
            email = value[0].get("value") if isinstance(value, list) and value and isinstance(value[0], dict) else value
            _set_email(session, scim_user, _email({"emails": [{"value": email, "primary": True}]}))
        # anything else (title, department, ...) isn't kept
    session.flush()
    sync_access(session, connection, scim_user)
    return scim_user


def _flatten_user_value(value: dict) -> dict:
    # Okta sends {"active": false}; some send dotted keys like {"name.givenName": "Pat"}.
    out: dict = {}
    for key, item in value.items():
        if key.lower().startswith("name."):
            out.setdefault("name", {})["givenName" if key.lower().endswith("givenname") else "familyName"] = item
        else:
            out[{"username": "userName", "externalid": "externalId", "displayname": "displayName"}.get(key.lower(), key)] = item
    return out


def deactivate_user(session: Session, connection: SsoConnection, scim_user: ScimUser) -> None:
    scim_user.active = False
    session.flush()
    sync_access(session, connection, scim_user)


# --- Groups --------------------------------------------------------------------------------


def group_resource(session: Session, group: ScimGroup, base: str, *, members: bool = True) -> dict:
    resource = {
        "schemas": [GROUP_SCHEMA],
        "id": str(group.id),
        "displayName": group.display_name,
        "meta": {
            "resourceType": "Group",
            "created": group.created_at.isoformat() if group.created_at else None,
            "lastModified": group.updated_at.isoformat() if group.updated_at else None,
            "location": _location(base, "Groups", group.id),
        },
    }
    if group.external_id:
        resource["externalId"] = group.external_id
    if members:
        rows = session.execute(
            select(ScimUser).join(ScimGroupMember, ScimGroupMember.scim_user_id == ScimUser.id).where(ScimGroupMember.group_id == group.id)
        ).scalars().all()
        resource["members"] = [{"value": str(u.id), "display": u.user_name, "$ref": _location(base, "Users", u.id)} for u in rows]
    return resource


def _member_ids(session: Session, connection: SsoConnection, members: Any) -> list[uuid.UUID]:
    ids = []
    for member in members or []:
        value = member.get("value") if isinstance(member, dict) else member
        ids.append(get_user(session, connection, str(value)).id)
    return ids


def _set_members(session: Session, connection: SsoConnection, group: ScimGroup, add: list[uuid.UUID] = (), remove: list[uuid.UUID] = (),
                 replace: list[uuid.UUID] | None = None) -> None:
    current = {m.scim_user_id: m for m in session.execute(select(ScimGroupMember).where(ScimGroupMember.group_id == group.id)).scalars()}
    touched: set[uuid.UUID] = set()
    if replace is not None:
        remove = [uid for uid in current if uid not in replace]
        add = [uid for uid in replace if uid not in current]
    for uid in add:
        if uid not in current:
            session.add(ScimGroupMember(tenant_id=group.tenant_id, group_id=group.id, scim_user_id=uid))
            touched.add(uid)
    for uid in remove:
        if uid in current:
            session.delete(current[uid])
            touched.add(uid)
    session.flush()
    for uid in touched:
        sync_access(session, connection, session.get(ScimUser, uid))


def _resync_members(session: Session, connection: SsoConnection, group: ScimGroup) -> None:
    for uid in session.execute(select(ScimGroupMember.scim_user_id).where(ScimGroupMember.group_id == group.id)).scalars().all():
        sync_access(session, connection, session.get(ScimUser, uid))


def create_group(session: Session, connection: SsoConnection, payload: dict) -> ScimGroup:
    name = str(payload.get("displayName") or "").strip()
    if not name or len(name) > 255:
        raise ScimError(400, "displayName is required.", "invalidValue")
    if session.execute(select(ScimGroup.id).where(ScimGroup.connection_id == connection.id, ScimGroup.display_name == name)).first():
        raise ScimError(409, "A group with that displayName already exists.", "uniqueness")
    group = ScimGroup(tenant_id=connection.tenant_id, connection_id=connection.id, display_name=name,
                      external_id=(str(payload["externalId"]) if payload.get("externalId") else None))
    session.add(group)
    session.flush()
    _set_members(session, connection, group, add=_member_ids(session, connection, payload.get("members")))
    return group


def get_group(session: Session, connection: SsoConnection, group_id: str) -> ScimGroup:
    try:
        group = session.get(ScimGroup, uuid.UUID(group_id))
    except ValueError:
        group = None
    if group is None or group.connection_id != connection.id:
        raise ScimError(404, "Group not found.")
    return group


def replace_group(session: Session, connection: SsoConnection, group: ScimGroup, payload: dict) -> ScimGroup:
    if payload.get("displayName"):
        group.display_name = str(payload["displayName"]).strip()[:255]
    if "externalId" in payload:
        group.external_id = str(payload["externalId"]) if payload["externalId"] else None
    session.flush()
    _set_members(session, connection, group, replace=_member_ids(session, connection, payload.get("members")))
    _resync_members(session, connection, group)  # a renamed group may map differently
    return group


_MEMBER_FILTER = re.compile(r'^members\[\s*value\s+eq\s+"([^"]+)"\s*\]$', re.IGNORECASE)


def patch_group(session: Session, connection: SsoConnection, group: ScimGroup, payload: dict) -> ScimGroup:
    renamed = False
    for kind, path, value in _operations(payload):
        lowered = (path or "").lower()
        if kind in ("add", "replace") and (path is None and isinstance(value, dict)):
            if value.get("displayName"):
                group.display_name, renamed = str(value["displayName"]).strip()[:255], True
            if "members" in value:
                ids = _member_ids(session, connection, value["members"])
                _set_members(session, connection, group, replace=ids) if kind == "replace" else _set_members(session, connection, group, add=ids)
        elif lowered == "displayname" and kind in ("add", "replace"):
            group.display_name, renamed = str(value).strip()[:255], True
        elif lowered == "members":
            ids = _member_ids(session, connection, value)
            if kind == "add":
                _set_members(session, connection, group, add=ids)
            elif kind == "remove":
                _set_members(session, connection, group, remove=ids) if ids else _set_members(session, connection, group, replace=[])
            else:
                _set_members(session, connection, group, replace=ids)
        elif kind == "remove" and (match := _MEMBER_FILTER.match(path or "")):
            _set_members(session, connection, group, remove=[get_user(session, connection, match.group(1)).id])
    session.flush()
    if renamed:
        _resync_members(session, connection, group)
    return group


def delete_group(session: Session, connection: SsoConnection, group: ScimGroup) -> None:
    _set_members(session, connection, group, replace=[])
    session.delete(group)
    session.flush()


# --- Patch and filters ---------------------------------------------------------------------


def _operations(payload: dict) -> list[tuple[str, str | None, Any]]:
    if PATCH_SCHEMA not in (payload.get("schemas") or [PATCH_SCHEMA]):
        raise ScimError(400, "Not a PatchOp request.", "invalidSyntax")
    out = []
    for op in payload.get("Operations") or []:
        kind = str(op.get("op", "")).lower()
        if kind not in ("add", "replace", "remove"):
            raise ScimError(400, f"Unsupported op {op.get('op')!r}.", "invalidSyntax")
        out.append((kind, op.get("path"), op.get("value")))
    return out


_FILTER = re.compile(r'^\s*([A-Za-z.]+)\s+eq\s+"((?:[^"\\]|\\.)*)"\s*$', re.IGNORECASE)


@dataclass(frozen=True)
class Page:
    start_index: int  # 1-based
    count: int


def _filter(expression: str | None, allowed: dict[str, Any]):
    """SCIM filters as directories use them: `attribute eq "value"`. Anything else is refused."""
    if not expression:
        return None
    match = _FILTER.match(expression)
    if not match or match.group(1).lower() not in allowed:
        raise ScimError(400, "Only filters of the form attribute eq \"value\" on " + ", ".join(sorted(allowed)) + " are supported.", "invalidFilter")
    return allowed[match.group(1).lower()](match.group(2).replace('\\"', '"'))


def list_users(session: Session, connection: SsoConnection, filter_: str | None, page: Page) -> tuple[list[ScimUser], int]:
    query = select(ScimUser).where(ScimUser.connection_id == connection.id)
    condition = _filter(filter_, {
        "username": lambda v: func.lower(ScimUser.user_name) == v.lower(),
        "externalid": lambda v: ScimUser.external_id == v,
        "emails.value": lambda v: ScimUser.user_id.in_(select(User.id).where(func.lower(User.email) == v.lower())),
        "emails": lambda v: ScimUser.user_id.in_(select(User.id).where(func.lower(User.email) == v.lower())),
    })
    if condition is not None:
        query = query.where(condition)
    total = session.execute(select(func.count()).select_from(query.subquery())).scalar_one()
    rows = session.execute(query.order_by(ScimUser.created_at, ScimUser.id).offset(page.start_index - 1).limit(page.count)).scalars().all()
    return list(rows), total


def list_groups(session: Session, connection: SsoConnection, filter_: str | None, page: Page) -> tuple[list[ScimGroup], int]:
    query = select(ScimGroup).where(ScimGroup.connection_id == connection.id)
    condition = _filter(filter_, {
        "displayname": lambda v: func.lower(ScimGroup.display_name) == v.lower(),
        "externalid": lambda v: ScimGroup.external_id == v,
    })
    if condition is not None:
        query = query.where(condition)
    total = session.execute(select(func.count()).select_from(query.subquery())).scalar_one()
    rows = session.execute(query.order_by(ScimGroup.created_at, ScimGroup.id).offset(page.start_index - 1).limit(page.count)).scalars().all()
    return list(rows), total
