"""Builds docs/compliance/asvs.md, OpenClear against OWASP ASVS 5.0 (OWASP_PLAN.md OW-D3, OW-D4).

Three inputs:
- docs/security/asvs-5.0-scope.csv: every requirement, its level and whether it's in scope;
- docs/security/asvs-status.csv: each in-scope requirement's status, evidence and note;
- the tests: a test marked `@pytest.mark.asvs("6.2.12")` is evidence for that requirement, so
  the page can't name a test that doesn't exist.

    python scripts/asvs_crosswalk.py           # rewrite the page
    python scripts/asvs_crosswalk.py --check   # exit 1 if it's stale (the test runs this)
"""

import argparse
import collections
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCOPE = ROOT / "docs" / "security" / "asvs-5.0-scope.csv"
STATUS = ROOT / "docs" / "security" / "asvs-status.csv"
PAGE = ROOT / "docs" / "compliance" / "asvs.md"
STATUSES = ("Met", "Partly", "Not met", "Service provider's (CUEC)", "Not applicable")
_MARK = re.compile(r'@pytest\.mark\.asvs\("([0-9.]+)"\)\s*\n(?:@[^\n]*\n)*\s*(?:async\s+)?def\s+(test_\w+)')


def test_marks() -> dict[str, list[str]]:
    """{"V6.2.12": ["tests/test_auth/test_x.py::test_y", ...]}"""
    marks: dict[str, list[str]] = collections.defaultdict(list)
    for path in sorted((ROOT / "tests").rglob("test_*.py")):
        for requirement, name in _MARK.findall(path.read_text(encoding="utf-8")):
            marks["V" + requirement].append(f"{path.relative_to(ROOT).as_posix()}::{name}")
    return marks


def load() -> tuple[list[dict], dict[str, dict], dict[str, list[str]]]:
    scope = list(csv.DictReader(SCOPE.open(encoding="utf-8")))
    status = {r["req_id"]: r for r in csv.DictReader(STATUS.open(encoding="utf-8"))}
    return scope, status, test_marks()


def _evidence(row: dict, tests: list[str]) -> str:
    parts = [p.strip() for p in row["evidence"].split(";") if p.strip()]
    linked = [f"`{p}`" if not p.startswith("OC-") else p for p in parts]
    linked += [f"`{t.split('::')[1]}`" for t in tests]
    return ", ".join(linked) or "—"


def render() -> str:
    scope, status, marks = load()
    in_scope = [r for r in scope if r["in_scope"] == "yes"]
    counts = collections.Counter(status[r["req_id"]]["status"] for r in in_scope)
    lines = [
        "# OWASP ASVS 5.0",
        "",
        "<!-- Generated by scripts/asvs_crosswalk.py from docs/security/asvs-5.0-scope.csv, docs/security/asvs-status.csv",
        "     and the tests' asvs marks. Edit those, not this page. -->",
        "",
        "OpenClear measured against the [OWASP Application Security Verification Standard 5.0]"
        "(https://owasp.org/www-project-application-security-verification-standard/), at Level 2, and Level 3 in "
        "V6–V11 and V16 ([ADR 0001](../adr/0001-asvs-level-2-with-level-3-for-identity-and-money.md)). The assessment was "
        "OpenClear's own; an independent penetration test is planned. It isn't legal advice ([Compliance](README.md)).",
        "",
        "**Evidence** names the code or document that meets the requirement, and the tests that prove it (each test is "
        "marked with the requirement it proves, so this page can't name a test that doesn't exist). **Service provider's "
        "(CUEC)** means it depends on whoever runs the installation ([CUECs](cuecs.md)).",
        "",
        f"{len(in_scope)} requirements in scope ({len(scope) - len(in_scope)} more are above the target level or don't apply "
        "to OpenClear at all, such as WebRTC):",
        "",
        "| Status | Requirements |",
        "|---|---|",
    ]
    lines += [f"| {s} | {counts.get(s, 0)} |" for s in STATUSES]
    lines += ["", "Requirements not fully met are recorded with their reason, here and in "
              "[OWASP_PLAN.md](../../plans/OWASP_PLAN.md).", ""]
    chapter = None
    for r in in_scope:
        if r["chapter"] != chapter:
            chapter = r["chapter"]
            lines += ["", f"## {r['req_id'].split('.')[0]} {chapter}", "",
                      "| Requirement | Level | Status | Evidence | Note |", "|---|---|---|---|---|"]
        row = status[r["req_id"]]
        text = r["requirement"].replace("|", "\\|")
        text = text if len(text) <= 160 else text[:157].rstrip() + "…"
        lines.append(f"| **{r['req_id']}** {text} | {r['level']} | {row['status']} | "
                     f"{_evidence(row, marks.get(r['req_id'], []))} | {row['note'].replace('|', chr(92) + '|') or ''} |")
    return "\n".join(lines) + "\n"


def problems() -> list[str]:
    """What's inconsistent: an unknown status, a Met row without evidence, missing files."""
    scope, status, marks = load()
    found = []
    for r in (r for r in scope if r["in_scope"] == "yes"):
        row = status.get(r["req_id"])
        if row is None:
            found.append(f"{r['req_id']}: no status")
            continue
        if row["status"] not in STATUSES:
            found.append(f"{r['req_id']}: unknown status {row['status']!r}")
        evidence = [p.strip() for p in row["evidence"].split(";") if p.strip()]
        if row["status"] in ("Met", "Partly") and not evidence and not marks.get(r["req_id"]):
            found.append(f"{r['req_id']}: {row['status']} without evidence")
        for path in evidence:
            if not path.startswith("OC-") and not (ROOT / path).exists():
                found.append(f"{r['req_id']}: evidence {path} doesn't exist")
    unknown = set(marks) - {r["req_id"] for r in scope}
    found += [f"tests mark {u}, which isn't an ASVS 5.0 requirement" for u in sorted(unknown)]
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    page = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page:
            print(f"{PAGE.relative_to(ROOT)} is stale: run python scripts/asvs_crosswalk.py", file=sys.stderr)
            return 1
        return 0
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
