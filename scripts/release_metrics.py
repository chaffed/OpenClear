"""Security metrics for a release (OWASP_PLAN.md OW-D14): ASVS 5.0 coverage, the advisories it
fixes, how old its dependencies are, and its SBOM. Run at release time:

    python scripts/release_metrics.py 1.26.0            # rewrite docs/compliance/security-metrics.md
    python scripts/release_metrics.py 1.26.0 --notes    # also print the section for the release notes

The page goes in the TPRM pack (docs/compliance/tprm.md); the section goes at the end of the
GitHub release's body. Advisories come from GitHub (the gh CLI, signed in); dependency ages from
PyPI's JSON API. Either being unreachable leaves its line saying so, rather than failing."""

import argparse
import collections
import csv
import datetime as dt
import json
import re
import statistics
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "compliance" / "security-metrics.md"
REPO = "chaffed/OpenClear"


def asvs() -> dict:
    scope = {r["req_id"]: r for r in csv.DictReader((ROOT / "docs/security/asvs-5.0-scope.csv").open(encoding="utf-8"))}
    status = collections.Counter(r["status"] for r in csv.DictReader((ROOT / "docs/security/asvs-status.csv").open(encoding="utf-8"))
                                 if scope.get(r["req_id"], {}).get("in_scope") == "yes")
    applicable = sum(status.values()) - status["Not applicable"]
    return {"met": status["Met"], "partly": status["Partly"], "not_met": status["Not met"],
            "cuec": status["Service provider's (CUEC)"], "applicable": applicable}


def advisories(version: str) -> list[str] | None:
    """The published advisories whose fix is this version."""
    try:
        out = subprocess.run(["gh", "api", f"repos/{REPO}/security-advisories?state=published&per_page=100"],
                             capture_output=True, text=True, check=True, timeout=60).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    found = []
    for advisory in json.loads(out):
        patched = {p for v in advisory.get("vulnerabilities") or [] for p in re.split(r"[,\s]+", v.get("patched_versions") or "")}
        if version in patched:
            found.append(f"{advisory['ghsa_id']} ({advisory.get('severity') or 'unrated'}): {advisory['summary']}")
    return found


def dependency_ages(today: dt.date) -> dict | None:
    """For each pinned runtime dependency, how long ago its pinned release came out, and
    whether a newer one exists."""
    pins = re.findall(r"^([A-Za-z0-9_.\-]+)==([^\s\\;]+)", (ROOT / "requirements/runtime.txt").read_text(), re.M)
    ages, behind = [], 0
    try:
        for name, version in pins:
            with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/json", timeout=20) as response:
                info = json.load(response)
            files = info["releases"].get(version) or []
            if files:
                released = min(dt.datetime.fromisoformat(f["upload_time_iso_8601"].replace("Z", "+00:00")) for f in files).date()
                ages.append((today - released).days)
            behind += info["info"]["version"] != version
    except OSError:
        return None
    return {"count": len(pins), "median_days": int(statistics.median(ages)) if ages else 0,
            "over_a_year": sum(a > 365 for a in ages), "behind_latest": behind}


def render(version: str, today: dt.date) -> tuple[str, str]:
    a, fixed, deps = asvs(), advisories(version), dependency_ages(today)
    sbom = f"https://github.com/{REPO}/releases/download/v{version}/openclear-{version}.cdx.json"
    lines = [
        f"- **ASVS 5.0:** {a['met']} of {a['applicable']} applicable requirements met ({100 * a['met'] // a['applicable']}%), "
        f"{a['partly']} partly, {a['not_met']} not met, {a['cuec']} the service provider's "
        "([crosswalk](https://github.com/chaffed/OpenClear/blob/main/docs/compliance/asvs.md)).",
        ("- **Advisories fixed:** could not be read from GitHub." if fixed is None else
         "- **Advisories fixed:** none." if not fixed else "- **Advisories fixed:** " + "; ".join(fixed) + "."),
        ("- **Dependencies:** PyPI could not be reached." if deps is None else
         f"- **Dependencies:** {deps['count']} pinned at runtime; their releases' median age is {deps['median_days']} days; "
         f"{deps['over_a_year']} are over a year old; {deps['behind_latest']} have a newer release (Dependabot and the weekly "
         "lock refresh propose them; one with a known vulnerability fails the build)."),
        f"- **SBOM:** [openclear-{version}.cdx.json]({sbom}) (CycloneDX).",
    ]
    notes = "### Security metrics\n\n" + "\n".join(lines) + "\n"
    page = "\n".join([
        "# Security metrics",
        "",
        "<!-- Generated by scripts/release_metrics.py at each release. -->",
        "",
        f"For OpenClear {version}, released {today.isoformat()}: part of the due-diligence pack ([third-party "
        "risk](tprm.md)). Each release's notes on GitHub carry the same figures for that release.",
        "",
        *lines,
        "",
        "Every change also passes CodeQL, Bandit, gitleaks, `pip-audit` and an OWASP ZAP baseline scan; ZAP's active scan "
        "runs weekly. How vulnerabilities are reported and how fast they're fixed: [SECURITY.md](../../SECURITY.md).",
        "",
    ])
    return page, notes


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("version")
    parser.add_argument("--notes", action="store_true", help="print the release notes' section")
    args = parser.parse_args()
    page, notes = render(args.version, dt.date.today())
    PAGE.write_text(page, encoding="utf-8")
    print(notes if args.notes else f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
