from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "openapi" / "openclear-v1.json"
PY_OUT = ROOT / "sdks" / "python" / "src" / "openclear_sdk" / "_generated.py"
