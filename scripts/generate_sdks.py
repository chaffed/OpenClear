"""Generates the typed part of the Python and TypeScript SDKs (SDK_PLAN.md P1) from the
published API contract, openapi/openclear-v1.json:

- sdks/python/src/openclear_sdk/_generated.py
- sdks/typescript/src/generated.ts
- sdks/dotnet/src/OpenClear/Generated.cs

Each holds the API's models (TypedDicts / interfaces) and one class per API area with a
method per endpoint. Everything else (tokens, retries, paging, bulk, webhooks, errors) is
the hand-written layer next to it. Run after regenerating the contract:

    python scripts/export_openapi.py && python scripts/generate_sdks.py

tests/test_sdk/test_generated_up_to_date.py fails when either file is stale. The generated
files are Apache-2.0 like the rest of the SDKs (SDK_PLAN.md X1)."""

