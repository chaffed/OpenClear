# Interactive sign-in (password, WebAuthn) is for people in a browser; the token endpoint is
# the hand-written layer's job.
SKIPPED_TAGS = {"auth", "webauthn", "oauth"}
METHODS = ("get", "post", "put", "patch", "delete")
HEADER = "Generated by scripts/generate_sdks.py from openapi/openclear-v1.json. Don't edit; regenerate."


# --- Reading the contract ------------------------------------------------------------------


@dataclass
class Param:
    name: str
    location: str  # path, query
    required: bool
    schema: dict
    description: str = ""


@dataclass
class Operation:
    tag: str
    name: str
    method: str
    path: str
    summary: str
    description: str
    params: list[Param]
    body_kind: str | None  # json, multipart, form
    body_schema: dict | None
    body_required: bool
    responses: list[dict]  # JSON schemas of the 2xx responses
    raw_response: bool  # a file (CSV, ...) rather than JSON
    platform: bool
    paginated: bool = field(default=False)


def _operation_name(op: dict) -> str:
    return op["operationId"].split("_api_v1")[0]


def read_operations(spec: dict) -> list[Operation]:
    operations = []
    for path, item in spec["paths"].items():
        for method in METHODS:
            op = item.get(method)
            if not op:
                continue
            tag = (op.get("tags") or ["default"])[0]
            if tag in SKIPPED_TAGS:
                continue
            params = [
                Param(p["name"], p["in"], bool(p.get("required")), p.get("schema", {}), p.get("description", ""))
                for p in op.get("parameters", []) if p["in"] in ("path", "query")
            ]
            body = op.get("requestBody") or {}
            content = body.get("content", {})
            body_kind, body_schema = None, None
            if "application/json" in content:
                body_kind, body_schema = "json", content["application/json"].get("schema", {})
            elif "multipart/form-data" in content:
                body_kind, body_schema = "multipart", content["multipart/form-data"].get("schema", {})
            elif "application/x-www-form-urlencoded" in content:
                body_kind, body_schema = "form", content["application/x-www-form-urlencoded"].get("schema", {})
            responses, raw = [], False
            for code, response in sorted(op.get("responses", {}).items()):
                if not code.startswith("2"):
                    continue
                media = response.get("content") or {}
                if "application/json" in media:
                    responses.append(media["application/json"].get("schema", {}))
                elif media:
                    raw = True
            security = {name for requirement in op.get("security", []) for name in requirement}
            operation = Operation(
                tag=tag, name=_operation_name(op), method=method.upper(), path=path, summary=op.get("summary", ""),
                description=(op.get("description") or "").strip(), params=params, body_kind=body_kind,
                body_schema=body_schema, body_required=bool(body.get("required")), responses=responses,
                raw_response=raw and not responses, platform="APIKeyHeader" in security,
            )
            names = {p.name for p in params if p.location == "query"}
            is_list = any(r.get("type") == "array" for r in responses)
            operation.paginated = is_list and "limit" in names and ("offset" in names or "after" in names)
            operations.append(operation)
    return operations


def resolve(spec: dict, schema: dict) -> dict:
    while "$ref" in schema:
        schema = spec["components"]["schemas"][schema["$ref"].split("/")[-1]]
    return schema


def model_name(name: str) -> str:
    """A schema's name as a type name: Pydantic's "FeeOverride-Input" becomes FeeOverrideInput."""
    return re.sub(r"[^0-9A-Za-z_]", "", name)


def ref_name(schema: dict) -> str | None:
    return model_name(schema["$ref"].split("/")[-1]) if "$ref" in schema else None


# --- Naming --------------------------------------------------------------------------------


def snake(name: str) -> str:
    return re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower()


def camel(name: str) -> str:
    head, *rest = snake(name).split("_")
    return head + "".join(word.capitalize() for word in rest)


def pascal(name: str) -> str:
    return "".join(word.capitalize() for word in snake(name).split("_"))


def py_ident(name: str) -> str:
    ident = snake(name)
    return ident + "_" if keyword.iskeyword(ident) else ident


def doc_lines(op: Operation) -> list[str]:
    lines = [op.summary + ".", "", f"{op.method} {op.path}"]
    if op.description:
        lines += ["", *op.description.splitlines()]
    return lines


# --- Python --------------------------------------------------------------------------------


def is_file(schema: dict) -> bool:
    """An uploaded file: `format: binary` (OpenAPI 3.0 style) or `contentMediaType` (3.1)."""
    if schema.get("type") == "array":
        return is_file(schema.get("items", {}))
    if "anyOf" in schema:
        return any(is_file(option) for option in schema["anyOf"])
    return schema.get("type") == "string" and (schema.get("format") == "binary" or "contentMediaType" in schema)


def py_type(schema: dict) -> str:
    if not schema:
        return "Any"
    if name := ref_name(schema):
        return name
    if "anyOf" in schema or "oneOf" in schema:
        parts = []
        for option in schema.get("anyOf") or schema.get("oneOf"):
            t = "None" if option.get("type") == "null" else py_type(option)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return py_type(schema["allOf"][0])
    if "enum" in schema:
        return "Literal[" + ", ".join(json.dumps(v) for v in schema["enum"]) + "]"
    kind = schema.get("type")
    if kind == "string":
        return "BinaryIO | bytes" if is_file(schema) else "str"
    if kind == "integer":
        return "int"
    if kind == "number":
        return "float"
    if kind == "boolean":
        return "bool"
    if kind == "array":
        return f"list[{py_type(schema.get('items', {}))}]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"dict[str, {py_type(extra) if isinstance(extra, dict) else 'Any'}]"
    return "Any"


def _optional(t: str) -> str:
    return t if t.endswith("| None") or t in ("None", "Any") else f"{t} | None"


def py_models(spec: dict) -> list[str]:
    out = []
    for raw_name, schema in sorted(spec["components"]["schemas"].items()):
        if raw_name in ("HTTPValidationError", "ValidationError") or raw_name.startswith("Body_"):
            continue
        name = model_name(raw_name)
        if schema.get("type") == "object" and "properties" in schema:
            required = set(schema.get("required", []))
            fields = []
            for prop, prop_schema in schema["properties"].items():
                t = py_type(prop_schema)
                fields.append((prop, t if prop in required else f"NotRequired[{t}]"))
            doc = (schema.get("description") or "").strip()
            if all(p.isidentifier() and not keyword.iskeyword(p) for p, _ in fields):
                out.append(f"class {name}(TypedDict):")
                if doc:
                    out.append(f'    """{doc}"""')
                    out.append("")
                out += [f"    {p}: {t}" for p, t in fields] or ["    pass"]
            else:
                body = ", ".join(f"{json.dumps(p)}: {t}" for p, t in fields)
                out.append(f"{name} = TypedDict({json.dumps(name)}, {{{body}}})")
        else:
            out.append(f"{name} = {py_type(schema)}")
        out += ["", ""]
    return out


def py_return(op: Operation) -> str:
    if op.raw_response:
        return "bytes"
    if not op.responses:
        return "None"
    types = []
    for schema in op.responses:
        t = py_type(schema)
        if t not in types:
            types.append(t)
    return " | ".join(types)


def py_item_type(op: Operation) -> str:
    for schema in op.responses:
        if schema.get("type") == "array":
            return py_type(schema.get("items", {}))
    return "Any"


def py_operation(spec: dict, op: Operation, *, iterate: bool = False) -> list[str]:
    path_params = [p for p in op.params if p.location == "path"]
    query_params = [p for p in op.params if p.location == "query" and not (iterate and p.name == "offset")]
    args = ["self"] + [f"{py_ident(p.name)}: {py_type(p.schema)}" for p in path_params]
    form_fields: list[tuple[str, str, bool, bool]] = []  # name, type, required, is_file
    if op.body_kind == "json":
        t = py_type(op.body_schema or {})
        args.append(f"body: {t}" if op.body_required else f"body: {t} | None = None")
    elif op.body_kind in ("multipart", "form"):
        body = resolve(spec, op.body_schema or {})
        required = set(body.get("required", []))
        for prop, prop_schema in body.get("properties", {}).items():
            upload = is_file(prop_schema)
            form_fields.append((prop, "FileInput" if upload else py_type(prop_schema), prop in required, upload))
        args += [f"{py_ident(n)}: {t}" for n, t, req, _ in form_fields if req]
    keyword_args = [f"{py_ident(p.name)}: {_optional(py_type(p.schema))} = None" for p in query_params]
    keyword_args += [f"{py_ident(n)}: {_optional(t)} = None" for n, t, req, _ in form_fields if not req]
    if keyword_args:
        args.append("*")
        args += keyword_args

    if iterate:
        name = re.sub(r"^list_", "iter_", op.name) if op.name.startswith("list_") else f"iter_{op.name}"
        returns = f"Iterator[{py_item_type(op)}]"
    else:
        name, returns = py_ident(op.name), py_return(op)
    path = op.path
    for p in path_params:
        path = path.replace("{" + p.name + "}", "{_path(" + py_ident(p.name) + ")}")
    lines = [f"    def {name}({', '.join(args)}) -> {returns}:"]
    docs = doc_lines(op)
    if iterate:
        docs = [f"Every row of {op.name}, following each page's `Link: rel=\"next\"`.", "", f"{op.method} {op.path}"]
    lines.append('        """' + docs[0])
    lines += [("        " + line).rstrip() for line in docs[1:]]
    lines.append('        """')
    call = [f'"{op.method}"', f'f"{path}"' if path_params else f'"{path}"']
    if query_params:
        call.append("query={" + ", ".join(f'"{p.name}": {py_ident(p.name)}' for p in query_params) + "}")
    if op.body_kind == "json":
        call.append("json=body")
    elif form_fields:
        data = [f'"{n}": {py_ident(n)}' for n, _, _, is_file in form_fields if not is_file]
        files = [f'"{n}": {py_ident(n)}' for n, _, _, is_file in form_fields if is_file]
        if data:
            call.append("data={" + ", ".join(data) + "}")
        if files:
            call.append("files={" + ", ".join(files) + "}")
    if op.platform:
        call.append('auth="platform"')
    if iterate:
        lines.append(f"        return self._c.paginate({', '.join(call)})")
    else:
        if op.raw_response:
            call.append("raw=True")
        lines.append(f"        return self._c.call({', '.join(call)})")
    return lines + [""]


def python(spec: dict, operations: list[Operation]) -> str:
    out = [
        "# SPDX-License-Identifier: Apache-2.0",
        f"# {HEADER}",
        f"# API version {spec['info']['version']}.",
        "",
        '"""The API\'s models and endpoints, generated from the OpenAPI contract."""',
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Iterator",
        "from typing import TYPE_CHECKING, Any, BinaryIO, Literal, NotRequired, TypedDict",
        "from urllib.parse import quote",
        "",
        "if TYPE_CHECKING:",
        "    from openclear_sdk.client import Transport",
        "",
        f"API_VERSION = {json.dumps(spec['info']['version'])}",
        "FileInput = BinaryIO | bytes | tuple[str, BinaryIO | bytes] | tuple[str, BinaryIO | bytes, str]",
        "",
        "",
        "def _path(value: Any) -> str:",
        '    return quote(str(value), safe="")',
        "",
        "",
        "# --- Models " + "-" * 82,
        "",
        "",
    ]
    out += py_models(spec)
    out += ["# --- Endpoints " + "-" * 79, "", ""]
    groups: dict[str, list[Operation]] = {}
    for op in operations:
        groups.setdefault(op.tag, []).append(op)
    for tag, ops in sorted(groups.items()):
        out.append(f"class {pascal(tag)}Api:")
        out.append(f'    """`{tag}` endpoints."""')
        out.append("")
        out.append('    def __init__(self, transport: "Transport") -> None:')
        out.append("        self._c = transport")
        out.append("")
        for op in sorted(ops, key=lambda o: (o.path, o.method)):
            out += py_operation(spec, op)
            if op.paginated:
                out += py_operation(spec, op, iterate=True)
        out += [""]
    out.append("AREAS = {")
    out += [f'    "{snake(tag)}": {pascal(tag)}Api,' for tag in sorted(groups)]
    out.append("}")
    return "\n".join(out).rstrip() + "\n"


# --- TypeScript ----------------------------------------------------------------------------


def ts_type(schema: dict) -> str:
    if not schema:
        return "unknown"
    if name := ref_name(schema):
        return name
    if "anyOf" in schema or "oneOf" in schema:
        parts = []
        for option in schema.get("anyOf") or schema.get("oneOf"):
            t = "null" if option.get("type") == "null" else ts_type(option)
            if t not in parts:
                parts.append(t)
        return " | ".join(parts)
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return ts_type(schema["allOf"][0])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "string":
        return "Blob" if is_file(schema) else "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        inner = ts_type(schema.get("items", {}))
        return f"Array<{inner}>"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
    return "unknown"


def ts_key(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)


def ts_models(spec: dict) -> list[str]:
    out = []
    for raw_name, schema in sorted(spec["components"]["schemas"].items()):
        if raw_name in ("HTTPValidationError", "ValidationError") or raw_name.startswith("Body_"):
            continue
        name = model_name(raw_name)
        doc = (schema.get("description") or "").strip()
        if doc:
            out.append("/** " + " ".join(doc.split()) + " */")
        if schema.get("type") == "object" and "properties" in schema:
            required = set(schema.get("required", []))
            out.append(f"export interface {name} {{")
            for prop, prop_schema in schema["properties"].items():
                out.append(f"  {ts_key(prop)}{'' if prop in required else '?'}: {ts_type(prop_schema)};")
            out.append("}")
        else:
            out.append(f"export type {name} = {ts_type(schema)};")
        out.append("")
    return out


def ts_return(op: Operation) -> str:
    if op.raw_response:
        return "Uint8Array"
    if not op.responses:
        return "void"
    types = []
    for schema in op.responses:
        t = ts_type(schema)
        if t not in types:
            types.append(t)
    return " | ".join(types)


def ts_operation(spec: dict, op: Operation, *, iterate: bool = False) -> list[str]:
    path_params = [p for p in op.params if p.location == "path"]
    query_params = [p for p in op.params if p.location == "query" and not (iterate and p.name == "offset")]
    args = [f"{camel(p.name)}: {ts_type(p.schema)}" for p in path_params]
    if op.body_kind == "json":
        args.append(f"body{'' if op.body_required else '?'}: {ts_type(op.body_schema or {})}")
    elif op.body_kind in ("multipart", "form"):
        body = resolve(spec, op.body_schema or {})
        required = set(body.get("required", []))
        fields = [f"{ts_key(prop)}{'' if prop in required else '?'}: {ts_type(s)}" for prop, s in body.get("properties", {}).items()]
        optional = not required
        args.append(f"form{'?' if optional else ''}: {{ {'; '.join(fields)} }}")
    if query_params:
        fields = "; ".join(f"{ts_key(p.name)}?: {ts_type(p.schema)}" for p in query_params)
        args.append(f"query: {{ {fields} }} = {{}}")
    path = op.path
    for p in path_params:
        path = path.replace("{" + p.name + "}", "${encodeURIComponent(String(" + camel(p.name) + "))}")
    options = []
    if query_params:
        options.append("query")
    if op.body_kind == "json":
        options.append("json: body")
    elif op.body_kind == "multipart":
        options.append("multipart: form")
    elif op.body_kind == "form":
        options.append("form")
    if op.platform:
        options.append('auth: "platform"')
    if iterate:
        name = camel(re.sub(r"^list_", "iter_", op.name) if op.name.startswith("list_") else f"iter_{op.name}")
        item = next((ts_type(r.get("items", {})) for r in op.responses if r.get("type") == "array"), "unknown")
        docs = [f"Every row of {camel(op.name)}, following each page's `Link: rel=\"next\"`.", "", f"{op.method} {op.path}"]
        sig, body_line = f"  {name}({', '.join(args)}): AsyncIterable<{item}> {{", f"    return this.c.paginate<{item}>(\"{op.method}\", `{path}`, {{ {', '.join(options)} }});"
    else:
        if op.raw_response:
            options.append("raw: true")
        returns = ts_return(op)
        docs = doc_lines(op)
        sig = f"  {camel(op.name)}({', '.join(args)}): Promise<{returns}> {{"
        body_line = f"    return this.c.call<{returns}>(\"{op.method}\", `{path}`, {{ {', '.join(options)} }});"
    lines = ["  /**"] + [("   * " + line.replace("*/", "*\\/")).rstrip() for line in docs] + ["   */", sig, body_line, "  }", ""]
    return lines


def typescript(spec: dict, operations: list[Operation]) -> str:
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        f"// {HEADER}",
        f"// API version {spec['info']['version']}.",
        "",
        'import type { Transport } from "./transport.ts";',
        "",
        f"export const API_VERSION = {json.dumps(spec['info']['version'])};",
        "",
        "// --- Models " + "-" * 82,
        "",
    ]
    out += ts_models(spec)
    out += ["// --- Endpoints " + "-" * 79, ""]
    groups: dict[str, list[Operation]] = {}
    for op in operations:
        groups.setdefault(op.tag, []).append(op)
    for tag, ops in sorted(groups.items()):
        out.append(f"/** `{tag}` endpoints. */")
        out.append(f"export class {pascal(tag)}Api {{")
        out.append("  private readonly c: Transport;")
        out.append("")
        out.append("  constructor(transport: Transport) {")
        out.append("    this.c = transport;")
        out.append("  }")
        out.append("")
        for op in sorted(ops, key=lambda o: (o.path, o.method)):
            out += ts_operation(spec, op)
            if op.paginated:
                out += ts_operation(spec, op, iterate=True)
        if out[-1] == "":
            out.pop()
        out += ["}", ""]
    out.append("export const AREAS = {")
    out += [f"  {camel(tag)}: {pascal(tag)}Api," for tag in sorted(groups)]
    out.append("} as const;")
    return "\n".join(out).rstrip() + "\n"


# --- C# --------------------------------------------------------------------------------------

CS_KEYWORDS = {"base", "class", "default", "event", "fixed", "namespace", "object", "operator", "params", "ref", "string", "out", "in", "is", "lock", "checked"}


def cs_ident(name: str) -> str:
    ident = camel(name)
    return "@" + ident if ident in CS_KEYWORDS else ident


_CS_SCHEMAS: dict = {}


def cs_type(schema: dict) -> str:
    """Wire types: strings stay strings (dates, ids, enums), so a value a newer server sends
    never fails to parse. A reference to an enum or alias becomes its underlying type."""
    if not schema:
        return "JsonElement"
    if name := ref_name(schema):
        target = _CS_SCHEMAS.get(schema["$ref"].split("/")[-1], {})
        if target.get("type") == "object" and "properties" in target:
            return name
        return cs_type(target)
    if "anyOf" in schema or "oneOf" in schema:
        options = [o for o in (schema.get("anyOf") or schema.get("oneOf")) if o.get("type") != "null"]
        types = {cs_type(o) for o in options}
        if len(types) == 1:
            return types.pop()
        if "string" in types:
            return "string"  # amounts accept a number or a string; send strings
        return "JsonElement"
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return cs_type(schema["allOf"][0])
    if "enum" in schema:
        return "string"
    kind = schema.get("type")
    if kind == "string":
        return "byte[]" if is_file(schema) else "string"
    if kind == "integer":
        return "long"
    if kind == "number":
        return "double"
    if kind == "boolean":
        return "bool"
    if kind == "array":
        return f"IReadOnlyList<{cs_type(schema.get('items', {}))}>"
    if kind == "object":
        return "IReadOnlyDictionary<string, JsonElement>"
    return "JsonElement"


def _cs_nullable(t: str) -> str:
    return t if t.endswith("?") else t + "?"


def cs_doc(text: str, indent: str) -> list[str]:
    lines = [line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") for line in text.splitlines()]
    return [f"{indent}/// <summary>"] + [f"{indent}/// {line}".rstrip() for line in lines] + [f"{indent}/// </summary>"]


def cs_models(spec: dict) -> list[str]:
    out = []
    for raw_name, schema in sorted(spec["components"]["schemas"].items()):
        if raw_name in ("HTTPValidationError", "ValidationError") or raw_name.startswith("Body_"):
            continue
        name = model_name(raw_name)
        doc = (schema.get("description") or "").strip()
        if schema.get("type") == "object" and "properties" in schema:
            required = set(schema.get("required", []))
            if doc:
                out += cs_doc(" ".join(doc.split()), "")
            out.append(f"public sealed record {name}")
            out.append("{")
            for prop, prop_schema in schema["properties"].items():
                t = cs_type(prop_schema)
                prop_name = pascal(prop) or "Value"
                if prop_name == name:
                    prop_name += "Value"
                if prop in required:
                    out.append(f'    [JsonPropertyName("{prop}")] public {t} {prop_name} {{ get; init; }} = default!;')
                else:
                    out.append(f'    [JsonPropertyName("{prop}")] [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] public {_cs_nullable(t)} {prop_name} {{ get; init; }}')
            out.append("}")
            out.append("")
    return out


def cs_return(op: Operation) -> str:
    if op.raw_response:
        return "byte[]"
    if not op.responses:
        return "JsonElement"
    types = []
    for schema in op.responses:
        t = cs_type(schema)
        if t not in types:
            types.append(t)
    return types[0] if len(types) == 1 else "JsonElement"


def cs_operation(spec: dict, op: Operation, *, iterate: bool = False) -> list[str]:
    path_params = [p for p in op.params if p.location == "path"]
    query_params = [p for p in op.params if p.location == "query" and not (iterate and p.name == "offset")]
    args = [f"{cs_type(p.schema)} {cs_ident(p.name)}" for p in path_params]
    form_fields: list[tuple[str, str, bool, bool]] = []
    if op.body_kind == "json":
        t = cs_type(op.body_schema or {})
        args.append(f"{t} body" if op.body_required else f"{_cs_nullable(t)} body = null")
    elif op.body_kind in ("multipart", "form"):
        body = resolve(spec, op.body_schema or {})
        required = set(body.get("required", []))
        for prop, prop_schema in body.get("properties", {}).items():
            upload = is_file(prop_schema)
            form_fields.append((prop, "FilePart" if upload else cs_type(prop_schema), prop in required, upload))
        args += [f"{t} {cs_ident(n)}" for n, t, req, _ in form_fields if req]
    optional = [f"{_cs_nullable(cs_type(p.schema))} {cs_ident(p.name)} = null" for p in query_params]
    optional += [f"{_cs_nullable(t)} {cs_ident(n)} = null" for n, t, req, _ in form_fields if not req]
    args += optional + ["CancellationToken cancellationToken = default"]

    path = op.path
    for p in path_params:
        path = path.replace("{" + p.name + "}", "{Uri.EscapeDataString(" + cs_ident(p.name) + ".ToString()!)}")
    path_expr = f'$"{path}"' if path_params else f'"{path}"'
    call = [f'"{op.method}"', path_expr]
    if query_params:
        call.append("query: new Dictionary<string, object?> { " + ", ".join(f'["{p.name}"] = {cs_ident(p.name)}' for p in query_params) + " }")
    if op.body_kind == "json":
        call.append("json: body")
    elif form_fields:
        call.append("form: new Dictionary<string, object?> { " + ", ".join(f'["{n}"] = {cs_ident(n)}' for n, _, _, _ in form_fields) + " }")
    if op.platform:
        call.append("platform: true")
    call.append("cancellationToken: cancellationToken")
    if iterate:
        name = pascal(re.sub(r"^list_", "iter_", op.name) if op.name.startswith("list_") else f"iter_{op.name}") + "Async"
        item = next((cs_type(r.get("items", {})) for r in op.responses if r.get("type") == "array"), "JsonElement")
        lines = cs_doc(f"Every row of {pascal(op.name)}Async, following each page's Link: rel=\"next\".\n{op.method} {op.path}", "    ")
        lines.append(f"    public IAsyncEnumerable<{item}> {name}({', '.join(args)}) =>")
        lines.append(f"        _c.PaginateAsync<{item}>({', '.join(call)});")
    else:
        returns = cs_return(op)
        lines = cs_doc("\n".join(doc_lines(op)), "    ")
        method = "CallRawAsync" if op.raw_response else f"CallAsync<{returns}>"
        lines.append(f"    public Task<{returns}> {pascal(op.name)}Async({', '.join(args)}) =>")
        lines.append(f"        _c.{method}({', '.join(call)});")
    return lines + [""]


def csharp(spec: dict, operations: list[Operation]) -> str:
    _CS_SCHEMAS.clear()
    _CS_SCHEMAS.update(spec["components"]["schemas"])
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        f"// {HEADER}",
        f"// API version {spec['info']['version']}.",
        "#nullable enable",
        "#pragma warning disable CS1591",
        "using System.Text.Json;",
        "using System.Text.Json.Serialization;",
        "",
        "namespace OpenClear;",
        "",
        "public static partial class ApiInfo",
        "{",
        f'    public const string Version = "{spec["info"]["version"]}";',
        "}",
        "",
    ]
    out += cs_models(spec)
    groups: dict[str, list[Operation]] = {}
    for op in operations:
        groups.setdefault(op.tag, []).append(op)
    for tag, ops in sorted(groups.items()):
        out += cs_doc(f"{tag} endpoints.", "")
        out.append(f"public sealed partial class {pascal(tag)}Api")
        out.append("{")
        out.append("    private readonly ITransport _c;")
        out.append(f"    public {pascal(tag)}Api(ITransport transport) => _c = transport;")
        out.append("")
        for op in sorted(ops, key=lambda o: (o.path, o.method)):
            out += cs_operation(spec, op)
            if op.paginated:
                out += cs_operation(spec, op, iterate=True)
        if out[-1] == "":
            out.pop()
        out += ["}", ""]
    out.append("public partial class OpenClearClient")
    out.append("{")
    for tag in sorted(groups):
        out.append(f"    public {pascal(tag)}Api {pascal(tag)} {{ get; private set; }} = default!;")
    out.append("")
    out.append("    private void BindAreas()")
    out.append("    {")
    for tag in sorted(groups):
        out.append(f"        {pascal(tag)} = new {pascal(tag)}Api(this);")
    out.append("    }")
    out.append("}")
    return "\n".join(out).rstrip() + "\n"


def generate() -> dict[Path, str]:
    spec = json.loads(SPEC.read_text())
    operations = read_operations(spec)
    return {PY_OUT: python(spec, operations), TS_OUT: typescript(spec, operations), CS_OUT: csharp(spec, operations)}


def main() -> int:
    for path, text in generate().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"Wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
