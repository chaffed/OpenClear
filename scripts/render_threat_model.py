"""Renders docs/security/threat-model.md from threat_model/openclear.py (OWASP_PLAN.md OW-D12).

    python scripts/render_threat_model.py           # rewrite the page
    python scripts/render_threat_model.py --check   # exit 1 if the page is stale (the test runs this)
"""

import argparse
import collections
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pytm import TM, Boundary, Dataflow  # noqa: E402

from threat_model.openclear import OPENCLEAR_THREATS, build  # noqa: E402

PAGE = ROOT / "docs" / "security" / "threat-model.md"
_SEVERITY_ORDER = {"Very High": 0, "High": 1, "Medium": 2, "Low": 3, "Very Low": 4}


def _diagram(tm: TM) -> str:
    elements = [e for e in TM._elements if not isinstance(e, (Dataflow, Boundary))]
    ids = {id(e): f"n{i}" for i, e in enumerate(elements)}
    lines = ["```mermaid", "flowchart LR"]
    for b, boundary in enumerate(TM._boundaries):
        lines.append(f'  subgraph b{b}["{boundary.name}"]')
        lines += [f'    {ids[id(e)]}["{e.name}"]' for e in elements if e.inBoundary is boundary]
        lines.append("  end")
    lines += [f'  {ids[id(e)]}["{e.name}"]' for e in elements if e.inBoundary is None]
    for f in TM._flows:
        lines.append(f'  {ids[id(f.source)]} -->|"{f.name}"| {ids[id(f.sink)]}')
    lines.append("```")
    return "\n".join(lines)


def _flows_table() -> str:
    rows = ["| Flow | From → to | Protocol | Data |", "|---|---|---|---|"]
    for f in TM._flows:
        data = ", ".join(sorted(d.name for d in f.data)) or "—"
        rows.append(f"| {f.name} | {f.source.name} → {f.sink.name} | {f.protocol} | {data} |")
    return "\n".join(rows)


def _openclear_threats() -> str:
    rows = ["| Id | STRIDE | Boundary | Threat | Mitigation | Evidence | Status |", "|---|---|---|---|---|---|---|"]
    for t in OPENCLEAR_THREATS:
        rows.append(f"| {t.id} | {t.stride} | {t.boundary} | {t.threat} | {t.mitigation} | {t.evidence} | {t.status} |")
    return "\n".join(rows)


def _generic_threats(tm: TM) -> str:
    by_threat: dict[str, dict] = {}
    targets: dict[str, set[str]] = collections.defaultdict(set)
    for f in tm.findings:
        by_threat.setdefault(f.threat_id, {"description": f.description, "severity": f.severity})
        targets[f.threat_id].add(f.target)
    order = sorted(by_threat, key=lambda t: (_SEVERITY_ORDER.get(by_threat[t]["severity"], 9), t))
    rows = ["| pytm id | Threat | Severity | Elements |", "|---|---|---|---|"]
    for t in order:
        rows.append(f"| {t} | {by_threat[t]['description']} | {by_threat[t]['severity']} | {', '.join(sorted(targets[t]))} |")
    return f"{len(tm.findings)} findings across {len(by_threat)} threats.\n\n" + "\n".join(rows)


def render() -> str:
    tm = build()
    tm.resolve()
    return f"""# Threat model

<!-- Generated by scripts/render_threat_model.py from threat_model/openclear.py. Edit those, not this page. -->

How OpenClear could be attacked, and what stops it. It's kept as code with
[OWASP pytm](https://github.com/OWASP/pytm) (`threat_model/openclear.py`) so it changes in the
same pull request as the system it describes, and a test fails when this page falls behind.
Terms are as in [CONTEXT.md](../../CONTEXT.md). It isn't legal advice, and it doesn't replace
each bank's own assessment of how it runs OpenClear.

## Data flows

{_diagram(tm)}

{_flows_table()}

## Threats specific to OpenClear

Positive pay's own threats, by [STRIDE](https://owasp.org/www-community/Threat_Modeling_Process)
category (Spoofing, Tampering, Repudiation, Information disclosure, Denial of service, Elevation
of privilege). Evidence names [OpenClear's controls](../compliance/controls.md), code and
ASVS 5.0 requirements. "CUEC" means the protection depends on the service provider or the bank
([CUECs](../compliance/cuecs.md)).

{_openclear_threats()}

## Generic threats (pytm's library)

pytm matches every element and flow against its threat library (based on CAPEC). These are
the threats it raises for this model, most severe first. Most are answered by the controls
above and by the [ASVS assessment](../../OWASP_PLAN.md); they're listed so that a change to
the model that raises a new one shows up in review.

{_generic_threats(tm)}

## Privacy (LINDDUN GO)

A pass over the [LINDDUN GO](https://linddun.org/go/) cards, by category:

| Category | OpenClear | Where |
|---|---|---|
| Linking | Records link to a bank, a customer and a person by design; nothing links people across banks except one person's own memberships, which only that person and each bank's admins see. | `db/tenancy.py::memberships_elsewhere` |
| Identifying | Check images and payee names identify people; access is by customer and account scope, and every view of an item is permission-checked. | OC-AC-03, OC-AC-04 |
| Non-repudiation | Decisions are deliberately attributable (the action log); that's a requirement of the bank's records, disclosed to its staff and customers. | OC-AU-01 |
| Detecting | Security events reveal sign-in patterns; they go only to the bank's own SIEM and carry no passwords, tokens or account numbers. | SIEM_PLAN.md, "What's never in an event" |
| Data disclosure | Outside services (cloud OCR, email, SMS) are off unless the bank turns them on and reviews them; the shared model pools labelled decisions only with the bank's acknowledgement. | OC-AC-11, `services/outside_services.py` |
| Unawareness | Customers' people see what's kept about their decisions in the action log their admins can read; the pooling disclosure is shown before a bank joins the shared model. | OC-AC-11 |
| Non-compliance | Retention periods are installation settings (finished jobs, notifications, upload results, exports, security events); the action log is kept and archived to signed files. Removing a departing bank's data is the service provider's job: there's no in-app offboarding yet. | `config.py` `retention_*`; OC-AU-03 |
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    args = parser.parse_args()
    page = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page:
            print(f"{PAGE.relative_to(ROOT)} is stale: run python scripts/render_threat_model.py", file=sys.stderr)
            return 1
        return 0
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(page, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
