"""Writes src/openclear/compliance/csf_data.py, the NIST CSF 2.0 crosswalk (CONTROLS_PLAN.md
CT6), from NIST's own mapping rather than by hand: the CSF 2.0 Reference Tool's download of
the Core with its informative references (https://csrc.nist.gov/projects/cprt, "Download the
Core"), which lists the SP 800-53 Rev. 5.1.1 controls behind each subcategory.

The copy it was made from is kept at tests/fixtures/crosswalks/csf-2.0-reference-tool.xlsx;
tests/test_compliance/test_crosswalks.py regenerates the module from it and fails when they
differ. To take a newer download, replace that file and run:

    python scripts/import_crosswalks.py

**SOC 2** (CT6): AICPA's "Mapping: 2017 Trust Services Criteria to NIST 800-53", downloaded
by whoever runs OpenClear under AICPA's terms, isn't redistributed: neither the file nor what's
made from it is in this repository. This reads your copy and writes the criteria and the
SP 800-53 Rev. 5 controls each lists (ids only, none of AICPA's text) to a JSON file outside
the repository's tracked files; OPENCLEAR_SOC2_MAPPING_PATH points OpenClear at it:

    python scripts/import_crosswalks.py soc2 third_party/aicpa-tsc-to-nist-800-53.xlsx \
        --out third_party/soc2-mapping.json
"""

import argparse
import json

import hashlib
import re
import sys
import warnings
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tests" / "fixtures" / "crosswalks" / "csf-2.0-reference-tool.xlsx"
OUT = ROOT / "src" / "openclear" / "compliance" / "csf_data.py"
REFERENCE = "SP 800-53 Rev 5.1.1: "
SUBCATEGORY = re.compile(r"^([A-Z]{2}\.[A-Z]{2}-\d{2}): (.*)$", re.S)
CONTROL = re.compile(r"^([A-Z]{2})-(\d{2})(?:\((\d{2})\))?$")  # NIST writes AC-02(01); the inventories AC-2(1)
FAMILY = re.compile(r"^[A-Z]{2}$")  # a reference to a whole family, such as IR


def _control_id(reference: str) -> str:
    if FAMILY.match(reference):
        return reference
    match = CONTROL.match(reference)
    if not match:
        raise ValueError(f"Unexpected SP 800-53 reference: {reference!r}")
    family, number, enhancement = match.groups()
    return f"{family}-{int(number)}" + (f"({int(enhancement)})" if enhancement else "")


def _order(control: str) -> tuple:
    """AC-2 before AC-2(1) before AC-10; a family before its controls."""
    family, _, rest = control.partition("-")
    number, _, enhancement = rest.rstrip(")").partition("(")
    return (family, int(number or 0), int(enhancement or 0))


def read(path: Path) -> dict[str, tuple[str, tuple[str, ...]]]:
    """Each subcategory's id, its text, and the SP 800-53 controls (or families) NIST lists for it.
    Withdrawn subcategories (moved into others in CSF 2.0) are left out."""
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="Workbook contains no default style")  # NIST's export has none
        sheet = openpyxl.load_workbook(path, read_only=True)["CSF 2.0"]
    out = {}
    for row in sheet.iter_rows(min_row=3, values_only=True):
        if not row[2]:
            continue
        match = SUBCATEGORY.match(row[2].strip())
        if not match:
            raise ValueError(f"Unexpected subcategory: {row[2]!r}")
        if match.group(2).startswith("[Withdrawn"):
            continue
        references = [line[len(REFERENCE):].strip() for line in (row[4] or "").splitlines() if line.startswith(REFERENCE)]
        out[match.group(1)] = (" ".join(match.group(2).split()), tuple(sorted({_control_id(r) for r in references}, key=_order)))
    return out


def render(path: Path) -> str:
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    lines = [
        "# SPDX-License-Identifier: AGPL-3.0-or-later",
        "# Copyright (C) 2026 Chaffed",
        "",
        '"""NIST CSF 2.0 subcategories and the SP 800-53 Rev. 5.1.1 controls NIST maps to each.',
        "Generated by scripts/import_crosswalks.py from NIST's CSF 2.0 Reference Tool download; don't",
        'edit by hand. A reference of two letters is a whole family (IR)."""',
        "",
        'SOURCE = "NIST CSF 2.0 Reference Tool, informative references to SP 800-53 Rev. 5.1.1"',
        'SOURCE_URL = "https://csrc.nist.gov/projects/cprt"',
        f'SOURCE_SHA256 = "{digest}"',
        "",
        "SUBCATEGORIES: dict[str, tuple[str, tuple[str, ...]]] = {",
    ]
    for key, (text, controls) in read(path).items():
        lines.append(f"    {key!r}: (")
        lines.append(f"        {text!r},")
        lines.append(f"        ({', '.join(repr(c) for c in controls)}{',' if len(controls) == 1 else ''}),")
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


SOC2_SHEET = "NIST 800-53 as Points of Focus"
SOC2_CRITERION = re.compile(r"^(CC\d|A1|C1|PI1|P\d)\.\d{1,2}$")
SOC2_REFERENCE = re.compile(r"^([A-Z]{2})-(\d{1,2})(\(\d{1,2}\))?(?:[a-z](?:\.\d+)?)?$")  # AC-2, AC-2(1), AC-2a: a statement part is its control


def read_soc2(path: Path) -> dict:
    """AICPA's TSC-to-800-53 workbook as {criterion: [800-53 controls]}, ids only."""
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", message="Workbook contains no default style")
        book = openpyxl.load_workbook(path, read_only=True)
    if SOC2_SHEET not in book.sheetnames:
        raise SystemExit(f"{path} has no {SOC2_SHEET!r} sheet: is it AICPA's TSC to NIST 800-53 mapping?")
    criteria: dict[str, set[str]] = {}
    for row in book[SOC2_SHEET].iter_rows(min_row=3, values_only=True):
        criterion, reference = (str(row[0]).strip() if row[0] else ""), (str(row[1]).strip() if row[1] else "")
        if not SOC2_CRITERION.match(criterion) or reference in ("", "None"):
            continue
        match = SOC2_REFERENCE.match(reference)
        if not match:
            raise SystemExit(f"Unexpected SP 800-53 reference {reference!r} for {criterion}")
        family, number, enhancement = match.groups()
        criteria.setdefault(criterion, set()).add(f"{family}-{int(number)}" + (f"({int(enhancement[1:-1])})" if enhancement else ""))
    overview = {str(r[0]).strip(): str(r[1]).strip() for r in book["Overview"].iter_rows(values_only=True) if r[0] and r[1]} \
        if "Overview" in book.sheetnames else {}
    return {"source": "AICPA, Mapping: 2017 Trust Services Criteria to NIST 800-53", "source_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "tsc_version": overview.get("Trust Services Criteria"), "nist_version": overview.get("NIST 800-53"),
            "criteria": {k: sorted(v, key=_order) for k, v in sorted(criteria.items(), key=lambda kv: _criterion_order(kv[0]))}}


def _criterion_order(criterion: str) -> tuple:
    series, _, number = criterion.partition(".")
    return (["CC", "A", "C", "PI", "P"].index(re.match(r"[A-Z]+", series).group(0)), series, int(number))


def main() -> None:
    parser = argparse.ArgumentParser(description="Write the CSF 2.0 crosswalk, or read your SOC 2 mapping.")
    parser.add_argument("which", nargs="?", choices=["csf", "soc2"], default="csf")
    parser.add_argument("source", nargs="?", help="the downloaded workbook (default for csf: the copy kept with the tests)")
    parser.add_argument("--out", default="third_party/soc2-mapping.json", help="soc2: where to write the mapping (keep it untracked)")
    args = parser.parse_args()
    if args.which == "csf":
        OUT.write_text(render(Path(args.source) if args.source else SOURCE), encoding="utf-8")
        print(f"Wrote {OUT}")
        return
    if not args.source:
        raise SystemExit("Give the path to AICPA's workbook.")
    data = read_soc2(Path(args.source))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8")
    print(f"Wrote {out}: {len(data['criteria'])} criteria. Set OPENCLEAR_SOC2_MAPPING_PATH={out} to use it.")


if __name__ == "__main__":
    main()
